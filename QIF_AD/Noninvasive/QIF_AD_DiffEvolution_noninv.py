from numba import njit
from CyRK import pysolve_ivp

# Loss function estimation
def LossFun(p, dt, Texp, Vexp):
   
    # proportional feedback coeffient
    K = 5;

    # parameters used in signal generation

    delta= p[0];    
    J    = p[1];
    etab = p[2];
    beta = p[3];
    taum = p[4];
    taua = 100;
    


   # gradient evaluation time
    Dt = 500
    # transient time
    Ttr = 1000
    
    nTtr = np.round((Ttr)/dt)
    nTtr = nTtr.astype(int)
    nDt = np.round((Ttr+Dt)/dt)
    nDt = nDt.astype(int)
    
    
    #tint = np.array([0, Dt])+Ttr
    tint = (Texp[nTtr], Texp[nDt])

    # Initial conditions
    yinit = np.array([0.1,1,0.1])#np.abs(np.random.randn(3))

    y0 = yinit

    args = (Texp,Vexp, delta,J,etab,beta,taum,taua, K)
    # First run: Transient dynamics
    sol_tr = pysolve_ivp(orig_mod,
                       (0, Texp[nTtr]),
                       y0,
                       args = args,
                       method = 'DOP853',
                       rtol=1e-6,
                       atol=1e-8
                       )
    x00 = sol_tr.y[:3, -1]  # Final state from transient
      
    # Second run: Gradient evaluation
    sol_eval = pysolve_ivp(orig_mod,
                         tint,
                         y0 = x00,
                         t_eval = Texp[nTtr:nDt],
                         args = args,
                         method = 'DOP853',
                         rtol=1e-6,
                         atol=1e-8)
    

