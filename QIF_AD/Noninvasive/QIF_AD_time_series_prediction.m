function QIF_AD_time_series_prediction()
% 
% Modeling macroscopic equations of QIF neuron network with spike frequency
% adaptation, according to "Low-dimensional model for adaptive
% networks of spiking neurons" by  B. Pietras, P. Clusella and E. Montbrió 
% https://doi.org/10.1103/PhysRevE.111.014422
%
% Compares macroscopic variable dynamics from microscopic modeling
% with macroscopic ODE results using optimized parameters.
%
%
    close all
    % clear all
    
    % timeseries from microscopic modeling
    load("time_series/QIF_AD_N1000_chaos.mat",'r','dt','Nt','PT','v','Aj');
    Yexp = [r v Aj];
    Texp = ((1:Nt)-1)*dt;
    
    P = PT;    

    % MEDIANS OF ESTIMATED PARAMETER VALUES
    P.delta = PT.delta *(1-0.013);
    P.J = PT.J*(1-0.005);
    P.etab = PT.etab*(1+0.009);
    P.beta = PT.beta*(1+0.004);
    P.taum  = PT.taum*(1-0.004);

    % feedback coefficient
    K = 5;
    % integration time
    Ttr= 1000; 
    Dt = 500; % gradient evaluation time
    

    yinit = [0.8,-5,4].';

    
    opts = odeset('RelTol',1e-7,'AbsTol',1e-9);
    
    
    interp_Yexp = griddedInterpolant(Texp,Yexp,"makima");

    tmp = interp_Yexp(0);
    yinit(2) = tmp(2);
    
    [Tc, Yc] = ode45(@(t,x)orig_mod(t,x,interp_Yexp,P,K),0:dt:Ttr,[yinit;0],opts);    
    xend=Yc(end,1:3).';
        
    [~, Yg] = ode45(@(t,x)orig_mod(t,x,interp_Yexp,P,K),[0 Dt]+Ttr,[xend;0],opts);

    Loss=Yg(end,4)/Dt;
    fprintf('Loss value: %f\n',Loss)

    Yexpg = interp_Yexp(Tc);
    
    createfigure1(Tc, [Yc(:,1),Yexpg(:,1)],[Yc(:,2),Yexpg(:,2)],[Yc(:,3),Yexpg(:,3)],Tc,Yc(:,1)-Yexpg(:,1), Yc(:,2)-Yexpg(:,2), Yc(:,3)-Yexpg(:,3))
    
    set(gcf, 'PaperSize', [16 7]);
    set(gcf,'Units','centimeters')
    set(gcf,'Position',[2,2,16,7])  

 end

% macroscopic ODE's
function dy =orig_mod(t,x,interp_Yexp,P,K)

    taum = P.taum;
    etab = P.etab;
    J = P.J;
    delta = P.delta;
    beta = P.beta;
    taua = P.taua;

    xexp  = interp_Yexp(t);
%     rt = xexp(1);
    vt = xexp(2);

    r = x(1);
    v = x(2);
    A = x(3);

    dy=zeros(4,1);

    %spiking rate R
    dy(1) = ( delta/((1+beta)*pi*taum)+2*r*v)/taum;
    %potencialas
    dy(2) = ( v^2 - (taum*pi*r)^2 + etab + J *taum*r-A +K*(vt-v))/taum;
    % adaptation variable
    dy(3) = ( -A*(1+beta) + beta*(etab+J*taum*r) )/taua;
    % loss function
    dy(4) = 0.5*(v - vt)^2;

end


