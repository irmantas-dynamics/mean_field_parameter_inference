"""
This script optimizes the parameters of the macroscopic equations for QIF neurons
to fit a signal generated by microscopic equation-based modeling. As a test case,
the macroscopic ODE is fitted to a signal generated by the same macroscopic equations.
The fitting is performed using only the mean membrane potential signal.

ODE is defined in  "Low-dimensional model for adaptive  networks of spiking neurons" by
B. Pietras, P. Clusella and E. Montbrió
https://doi.org/10.1103/PhysRevE.111.014422

To avoid dependence of the loss function on the initial conditions of the ODE the
microscopic equations is affected  with known external periodic  force, which syncrhonizes
the system.

Optimization is performed using Differential Evolution algorithm implemented in
scipy package. The algorithm uses parallel computing. Set the workers option in
differential_evolution() according to your CPU capabilities.

Script's input:

        Narray: array with strings representing neuron counts used for macroscopic signal
                generation, used for file with macroscopic signal loading.
                File name format "time_series/QIF_AD_N%s_chaos_ext.mat", where %s is element
                of Narray.
                
        nopt:   number of different DE optimization trials

Script writes results to file with name format - optimization_results/QIF_AD_%s_optim_results.csv
, where %s is neuron counts used for macroscopic signal generation. Columns correspond to
optimized parameters; the last column contains the optimized loss value.


"""
import time
import numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import differential_evolution
from scipy.interpolate import Akima1DInterpolator

import scipy.io as sio
import matplotlib.pyplot as plt

from functools import partial

# Loss function estimation
def LossFun(p,interp_Yexp, dt, Texp, Vexp):
    
    #external force parameters
    K ={'Amp': -4,
         'om': 2*np.pi/80,
       'Tper': 80
    }

    # parameters used in signal generation
    etab = 3.25;
    delta= 1;    
    J    = 20;
    taua = 100;
    taum = 10;
    beta = 1;


    # Dictionary of parameters used in the signal generation from microscopic eqs
    PT = {
            'taum':taum,
            'etab': etab,
            'J':J     ,
            'delta':delta ,
            'beta':beta  ,
            'taua':taua
        }

    # Dictionary for optimized parameter set
    P = PT.copy();

    P['delta'] = p[0]
    P['J'] = p[1]
    P['etab'] = p[2]
    P['beta']  = p[3]
    P['taum']  = p[4]
    ##P['taua']  = p[5]

    # gradient evaluation time
    Dt = 3 * K['Tper']
    # transient time
    Ttr = 30 * K['Tper']
    
    nTtr = np.round((Ttr)/dt)
    nTtr = nTtr.astype(int)
    nDt = np.round((Ttr+Dt)/dt)
    nDt = nDt.astype(int)
    
    
    #tint = np.array([0, Dt])+Ttr
    tint = [Texp[nTtr], Texp[nDt]]

    # Initial conditions
    yinit = np.abs(np.random.randn(3))

    y0 = yinit

    # First run: Transient dynamics
    sol_tr = solve_ivp(lambda t, x: orig_mod(t, x, interp_Yexp, P, K), [0, Texp[nTtr]], y0, rtol=1e-7, atol=1e-9)
    x00 = sol_tr.y[:3, -1]  # Final state from transient
      
    # Second run: Gradient evaluation
    sol_eval = solve_ivp(fun = lambda t, x: orig_mod(t, x, interp_Yexp, P, K),
                         t_span = tint,
                         y0 = x00,
                         t_eval = Texp[nTtr:nDt],
                         rtol=1e-7,
                         atol=1e-9)
    

#     fig, ax = plt.subplots()
#     ln1, = ax.plot(sol_eval.t, sol_eval.y[1],label ='pyODE')
#     ln2, = ax.plot(sol_eval.t, interp_Yexp(sol_eval.t),label='interp')
# 
#     ax.set(xlabel='time (s)', ylabel='voltage (mV)',
#        title='About as simple as it gets, folks')
#     ax.legend(handles = [ln1])
#     ax.grid()
#   
# 
#     fig.savefig("test.png")
#     plt.show()
    #Loss = 0.5*np.mean( (sol_eval.y[1, :] - interp_Yexp(sol_eval.t) )**2)
    Loss = 0.5*np.mean( (sol_eval.y[1, :] - Vexp[nTtr:nDt] )**2)
    return Loss

#  ODE whose parameters are subject to optimization
def orig_mod(t, x,interp_Yexp,P, K):
    # Model parameters
    taum = P['taum']
    etab = P['etab']
    J = P['J']
    delta = P['delta']
    beta = P['beta']
    taua = P['taua']

    r, v, A = x[0], x[1], x[2]


    Iext = K['Amp'] * (1 + np.sin(K['om'] * t) / 2) ** 3

    dxdt = np.zeros(3)

    # Simulated system
    dxdt[0] = (delta / ((1 + beta) * np.pi * taum) + 2 * r * v) / taum
    dxdt[1] = (v ** 2 - (taum * np.pi * r) ** 2 + etab + J  * taum * r - A + Iext) / taum
    dxdt[2] = (-A * (1 + beta) + beta * (etab + J * taum * r + Iext)) / taua


    return dxdt

def main():

    # Strings representing neuron counts used for macroscopic signal generation
    #Narray = [100,500,1000,10000,100000];
    Narray=['inf','100000','10000','1000','500','200']
    #Narray = [10000]

    # number of different DE optimization trials
    nopt = 1


    for ind in Narray:
        # loading macroscopic signal from file
        fname = "time_series/QIF_AD_N%s_chaos_ext.mat" % ind
        vrs = sio.loadmat(fname,squeeze_me = True)
        print("========\tFile:\t%s\t loaded\t ==============\n"% fname)

        # mean potential signal
        Vexp = vrs['v']
        # time
        Texp = vrs['tm']
        # integration step
        dt = Texp[1]-Texp[0]#vrs['dt']

        # Interpolate experimental signal for use in feedback (ODE integration)
        interp_Yexp = Akima1DInterpolator(Texp, Vexp, method="makima")

        # bound for parameter optimization
        # [ delta, J, etab, beta, taum ]
        bounds = [(0.9,2),  (10., 30.),  (1.75,4.9), (0.25,1.25),(7.,17.)]

        loss = partial(LossFun,interp_Yexp=interp_Yexp, dt=dt, Texp=Texp, Vexp=Vexp)

        # DE optimization trials
        for i1 in range(0,nopt):
         
            start_time = time.time()

            result = differential_evolution(loss,
                                            bounds,
                                            disp = True,
                                            popsize= 15,
                                            maxiter = 500,
                                            atol=1e-5,
                                            tol = 1e-5,
                                            workers = 10,
                                            polish = False,
                                            updating='deferred');

            print("\n--- %d iteration finished in" % (i1+1), end =' ')
            print(" %.2f seconds --- %s\n" % (time.time() - start_time,fname))
      
            # saving results in csv file
            fname2 = "optimization_results/QIF_AD_%s_optim_results_ext.csv" % ind
          
            print("Optimized parameters:")
            with open(fname2,"a") as f:
                for i2 in range(0,len(bounds)):
                    f.write("%f;" % result.x[i2])
                    print(result.x[i2], end=' ')
            
                print("\n\nValues of loss function:")
                print(result.fun)
                print()
                f.write("%f;\n" % result.fun)
                
            
        print("============================\n\n")

if __name__ == "__main__":
    main()





