function QIF_IN_time_series_prediction()
%
% Modeling network of QIF neurons with inhibitorry interaction, 
% according to "Firing rate equations require a spike synchrony mechanism
% to correctly describe fast oscillations in inhibitory networks" by
% F. Devalle, A. Roxin and E. Montbrió 
% https://doi.org/10.1371/journal.pcbi.1005881
%
% Compares macroscopic variable dynamics from microscopic modeling
% with macroscopic ODE results using optimized parameters.
%
%

    close all
    % clear all

    % timeseries from microscopic modeling
    load("time_series/QIF_IN_N1000.mat",'Rt','dt','Nt','PT','v','St');
    Yexp = [Rt v St];
    Texp = ((1:Nt)-1)*dt;


    P = PT;

    
    % MEDIANS OF ESTIMATED PARAMETER VALUES
     P.delta = PT.delta *(1-0.009);
     P.J = PT.J  *(1-0.006);
     P.etab = PT.etab *(1- 0.001);
     P.taum  = PT.taum*(1- 0.002);
     P.taua  = PT.taua*(1 + 0.003);

    
    % feedback coefficient
    K = 0.5;

    Tosc = 27.71;
    % integration time
    Ttr = 15*Tosc;


    yinit = [0.15,-5,0.1].';
    
    opts = odeset('RelTol',1e-7,'AbsTol',1e-9);
    
    interp_Yexp = griddedInterpolant(Texp,Yexp,"makima");

    tmp = interp_Yexp(0);
    yinit(2) = tmp(2);
    
    [Tc, Yc] = ode45(@(t,x)orig_mod(t,x,interp_Yexp,P,K),0:dt:Ttr,[yinit;0],opts);    

    Yexpg = interp_Yexp(Tc);
    
    createfigure1(Tc, [Yc(:,1),Yexpg(:,1)],[Yc(:,2),Yexpg(:,2)],[Yc(:,3),Yexpg(:,3)],Tc,Yc(:,1)-Yexpg(:,1), Yc(:,2)-Yexpg(:,2), Yc(:,3)-Yexpg(:,3))
    
    set(gcf, 'PaperSize', [16 7]);
    set(gcf,'Units','centimeters')
    set(gcf,'Position',[2,2,16,7])  

end

% macroscopic ODE's
function dy =orig_mod(t,x,interp_Yexp,P,K)

    taum = P.taum;
    etab = P.etab;
    J = P.J;
    Jdaug = 1;
    delta = P.delta;
    taua = P.taua;
    

    xexp  = interp_Yexp(t);
%     rt = xexp(1);
    vt = xexp(2);

    r = x(1);
    v = x(2);
    S = x(3);

    dy=zeros(4,1);

    %spiking rate R
    dy(1) = ( delta/(pi*taum)+2*r*v)/taum;
    %potencialas
    dy(2) = ( v^2 - (taum*pi*r)^2 + etab - J*Jdaug *taum*S +K*(vt-v))/taum;
    % adaptation variable
    dy(3) = ( -S + r)/taua;
    % loss function
    dy(4) = 0.5*(v - vt)^2;

end


