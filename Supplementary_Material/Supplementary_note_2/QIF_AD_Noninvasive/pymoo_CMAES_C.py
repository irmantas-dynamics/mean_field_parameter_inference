def infer_termination_reason(res, tol_f=1e-6, tol_x=1e-6):
    term = res.algorithm.termination
    algo = res.algorithm
    reasons = []

    # Check max generations
    if hasattr(term, "n_max_gen") and algo.n_gen >= term.n_max_gen:
        reasons.append(f"max generations reached ({algo.n_gen})")

    # Check max function evaluations
    if hasattr(term, "n_max_eval") and algo.n_eval >= term.n_max_eval:
        reasons.append(f"max evaluations reached ({algo.n_eval})")

    # Check small change in F
    if hasattr(term, "F_tol") and len(algo.history) > 1:
        # last F and previous F
        F_history = np.array([pop.get("F").min() for pop in algo.history])
        if np.abs(F_history[-1] - F_history[-2]) < tol_f:
            reasons.append(f"function improvement below F_tol ({tol_f})")

    # Check small change in X
    if hasattr(term, "X_tol") and len(algo.history) > 1:
        X_history = np.array([pop.get("X").mean(axis=0) for pop in algo.history])
        if np.linalg.norm(X_history[-1] - X_history[-2]) < tol_x:
            reasons.append(f"solution improvement below X_tol ({tol_x})")

    if len(reasons) == 0:
        reasons.append("unknown or multiple criteria triggered")

    return reasons

class MyOutput(Output):

    def __init__(self,n_var):
        super().__init__()
        self.par_colmn = []
        self.n_var = n_var
        for i1 in range(n_var):
            self.par_colmn.append(Column(f"p{i1}", width=10))
        
        #self.x_mean = Column("Param_mean", width=13)
        #self.x_min = Column("Param_min", width=13)
        self.F_min = Column("F_min", width=13)
        self.columns += self.par_colmn
        self.columns += [self.F_min]

    def update(self, algorithm):
        super().update(algorithm)
        #self.x_mean.set(np.mean(algorithm.pop.get("X")))
        #self.x_min.set(np.min(algorithm.pop.get("X")))
        X = algorithm.pop.get("X")
        F = algorithm.pop.get("F")
        idx_min = np.argmin(F)
        for i1 in range(self.n_var):
            self.par_colmn[i1].set(np.min(X[idx_min,i1]))
        self.F_min.set(np.min(algorithm.pop.get("F")))



# ---------------------------------------------------------------------------
# Loss function
# ---------------------------------------------------------------------------    
def LossFun(p, Texp, Vexp):
    """
    Vectorised loss function called by differential_evolution (vectorized=True).

    Parameters
    ----------
    p : ndarray, shape (5, n_params)
        Population matrix from DE; each column is one candidate:
        row 0 – delta, row 1 – J, row 2 – etab, row 3 – beta, row 4 – taum.
    Texp        : 1-D array – time axis of the experimental signal
    Vexp        : 1-D array – mean membrane potential from the microscopic sim

    Returns
    -------
    loss : 1-D array of length n_params
        0.5 * MSE(v_sim, V_exp) for each candidate, evaluated over a
        500 ms window that follows a 2000 ms transient burn-in.
    """

    
    # --- fixed parameters (not optimised) ---
    # These are the ground-truth values used when generating the signal;
    # kept here for reference 
    etab = 3.25;
    delta= 1;    
    J    = 20;
    taua = 100;
    taum = 10;
    beta = 1;
    
    dt = Texp[1]-Texp[0]
    
    p = np.ascontiguousarray(p, dtype=np.float64)  # ensure contiguous C layout for ctypes

    n_params = p.shape[1]

    # Unpack columns of the DE population matrix into per-parameter arrays
    # Order matches the bounds list: [ delta, J, etab, beta, taum ]
    delta_vals = p[0,:]
    J_vals     = p[1,:]
    etab_vals  = p[2,:]
    beta_vals  = p[3,:]
    taum_vals  = p[4,:]

    # Ensure arrays are contiguous float64 for C
    delta_vals = np.ascontiguousarray(delta_vals, dtype=np.float64)
    J_vals     = np.ascontiguousarray(J_vals, dtype=np.float64)
    etab_vals  = np.ascontiguousarray(etab_vals, dtype=np.float64)
    beta_vals  = np.ascontiguousarray(beta_vals, dtype=np.float64)
    taum_vals  = np.ascontiguousarray(taum_vals, dtype=np.float64)

    Texp = np.ascontiguousarray(Texp, dtype=np.float64)
    Vexp = np.ascontiguousarray(Vexp, dtype=np.float64)
    
    
    # Loss function evaluation time
    Dt = 500
    # transient time
    Ttr = 2000
    
    dT = Texp[1]-Texp[0]
    
    nTtr = np.round((Ttr)/dt)
    nTtr = nTtr.astype(int)
    nDt = np.round((Dt)/dt)
    nDt = nDt.astype(int)



    taua = 100.0
    K = 5.0
    
    # Output array for RMSE
    loss = np.empty(n_params, dtype=np.float64)

    # --- call the OpenMP-parallelised C batch evaluator ---
    lib.lossPar(
                taum_vals,
                etab_vals,
                J_vals,
                delta_vals,
                beta_vals,
                taua,
                n_params,
                K,
                Texp,
                Vexp,
                len(Texp),
                nTtr,
                nDt,
                loss
                )

    return loss


# ----------------------------------------------
# pymoo Problem with multiprocessing
# ----------------------------------------------
class MyProblem(Problem):

    def __init__(self,  Texp=None,Vexp =None,n_var=2,xl=None,xu =None):
        super().__init__(n_var=n_var, n_obj=1, xl= xl, xu= xu)

        self.Texp = Texp
        self.Vexp = Vexp

    def _evaluate(self, X, out, *args, **kwargs):
        
        F = LossFun(X.transpose(),self.Texp,self.Vexp);
        
        out["F"] = np.array(F)


