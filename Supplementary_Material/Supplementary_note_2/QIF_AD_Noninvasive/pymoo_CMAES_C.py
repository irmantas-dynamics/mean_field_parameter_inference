if __name__ == "__main__":
    """
    Entry point.

    For each neuron count in Narray:
      1. Load the microscopic simulation signal from a .mat file.
      2. Run nopt independent CMAES optimisations, each starting from a
         different random population.
      3. Append optimised parameters and loss values to a per-N CSV file.
         Timing for each trial is written to a shared time.csv.
    """

    Narray = [200,500,1000,10000,100000,'inf'];
    Narray = Narray[::-1];


    for ind in Narray:
        # --- load experimental (microscopic) signal ---
        fname = "time_series/QIF_AD_N%s_chaos.mat" % ind
        vrs = sio.loadmat(fname,squeeze_me = True)
        print("========\tFile:\t%s\t loaded\t ==============\n"% fname)

        # mean potential signal
        Vexp = vrs['v']
        # time
        Texp = vrs['tm']
        # integration step
        dt = Texp[1]-Texp[0]#vrs['dt']

        

        n_var = 5
        # Search bounds for [ delta, J, etab, beta, taum ]
        xl=[0.9,10.,1.75,0.25,7.]
        xu=[2.0,30.,4.9,1.25,17.]
        problem = MyProblem( Texp=Texp,Vexp = Vexp, n_var =n_var, xl= xl, xu=xu)
    
        termination = DefaultMultiObjectiveTermination(
                        xtol=1e-6,
                        ftol=1e-6,  # Very large value effectively disables this criterion
                        n_max_gen=500,  # Rely mainly on generation limit
                        n_max_evals=10000
                    )


        algorithm = CMAES()
        nopt = 10
        # --- CMAES optimisation trials ---
        for i1 in range(0,nopt):
            start_time = time.time()
            res = minimize(problem,
                       algorithm,
                       termination,
                       #seed=1,
                       output=MyOutput(n_var),
                       verbose=True)
    
            end_time = time.time()
            print("--- %d iteration finished in" % (i1+1), end =' ')
            total_time = (time.time() - start_time)
            print(" %s seconds ---\n" % total_time)
            
            # Append wall-clock time for this trial
            with open("optimization_results_CMAES/time.csv","a") as f:
                f.write("%s; %f\n" % (ind,total_time))
                
            # Append optimised parameters and final loss to the per-N CSV
            pav2 = "optimization_results_CMAES/QIF_AD_%s_optim_results.csv" % ind

            with open(pav2,"a") as f:
                for i2 in range(0,5):
                    f.write("%f;" % res.X[i2])
                    print(res.X[i2], end=' ')
            
                print(res.F[0])
                print()
                f.write("%f;\n" % res.F[0])
                
            
        print("============================\n\n")
            


    
