"""
This script optimizes the parameters of the macroscopic equations for QIF neurons
to fit a signal generated by microscopic equation-based modeling. 

ODE is defined in  "Low-dimensional model for adaptive  networks of spiking neurons" by
B. Pietras, P. Clusella and E. Montbrió
https://doi.org/10.1103/PhysRevE.111.014422
'
To avoid dependence of the loss function on the initial conditions of the ODE the
microscopic equations is affected  with known external periodic  force, which syncrhonizes
the system.

Optimization is performed using CMAES algorithm implemented in
pymoo package. The algorithm uses parallel computing.

Script's input:

        Narray: array with strings representing neuron counts used for macroscopic signal
                generation, used for file with macroscopic signal loading.
                File name format "time_series/QIF_AD_N%s_chaos.mat", where %s is element
                of Narray.
                
        nopt:   number of different DE optimization trials

Script writes results to file with name format - optimization_results_CMAES/QIF_AD_%s_optim_results.csv
, where %s is neuron counts used for macroscopic signal generation. Columns correspond to
optimized parameters; the last column contains the optimized loss value.


"""
