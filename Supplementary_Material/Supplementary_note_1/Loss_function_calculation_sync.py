"""
This script calculates loss function between the signal generated with the macroscopic equations of
 QIF AD neurons with true parameters and different initial conditions for r and A variables. 

 Loss function value is calculated WITH synchronization of the signals.

ODE is defined in  "Low-dimensional model for adaptive  networks of spiking neurons" by
B. Pietras, P. Clusella and E. Montbrió
https://doi.org/10.1103/PhysRevE.111.014422

To avoid dependence of the loss function on the initial conditions of the ODE,
the system model is augmented with proportional feedback by adding the difference
between the measured signal and the corresponding ODE state variable.


"""

import time
import numpy as np

import scipy.io as sio
import matplotlib.pyplot as plt

from joblib import Parallel, delayed

from functools import partial
from numba import njit
from CyRK import pysolve_ivp

# Loss function estimation
def LossFun(p, dt, Texp, Vexp):
   
    # proportional feedback coeffient
    K = 5;

    # parameters used in signal generation
    delta = 1;
    J = 20;
    etab = 3.25;
    beta = 1;
    taum = 10;
    taua = 100;

   # gradient evaluation time
    Dt = 500
    # transient time
    Ttr = 2000
    
    nTtr = np.round((Ttr)/dt)
    nTtr = nTtr.astype(int)
    nDt = np.round((Dt+Ttr)/dt)
    nDt = nDt.astype(int)
    
    
    #tint = np.array([0, Dt])+Ttr
    tint = (Texp[nTtr], Texp[nDt])

    # Initial conditions
    yinit = np.array([p[0], Vexp[0] , p[1]])

    y0 = yinit

    args = (Texp,Vexp, delta,J,etab,beta,taum,taua, K)
    # First run: Transient dynamics
    sol_tr = pysolve_ivp(orig_mod,
                       (0, Texp[nTtr]),
                       y0,
                       args = args,
                       method = 'DOP853',
                       rtol=1e-6,
                       atol=1e-8
                       )
    x00 = sol_tr.y[:3, -1]  # Final state from transient
      
    # Second run: Gradient evaluation
    sol_eval = pysolve_ivp(orig_mod,
                         tint,
                         y0 = x00,
                         t_eval = Texp[nTtr:nDt],
                         args = args,
                         method = 'DOP853',
                         rtol=1e-6,
                         atol=1e-8)
    
    Loss = 0.5*np.mean( (sol_eval.y[1, :] - Vexp[nTtr:nDt] )**2)
    return Loss

#  ODE whose parameters are subject to optimization
@njit
def orig_mod(t, x,Texp,Vexp, delta,J,etab,beta,taum,taua, K):

    r, v, A = x[0], x[1], x[2]

    dxdt = np.zeros(3)
    
    vt = np.interp(t,Texp,Vexp)

    # Simulated system
    dxdt[0] = (delta / ((1 + beta) * np.pi * taum) + 2 * r * v) / taum
    dxdt[1] = (v ** 2 - (taum * np.pi * r) ** 2 + etab + J * taum * r - A +K*(vt-v) ) / taum
    dxdt[2] = (-A * (1 + beta) + beta * (etab + J * taum * r )) / taua

    return dxdt

def main():
    
    #time series generated by  'QIF_AD/Noninvasive/QIF_AD_macro_time_series.m' script
    fname = "time_series/QIF_AD_Ninf_chaos.mat"
    vrs = sio.loadmat(fname,squeeze_me = True)
    
    # mean potential signal
    Vexp = vrs['v']
    # time
    Texp = vrs['tm']
    # integration step
    dt = Texp[1]-Texp[0]#vrs['dt']

   
    nr = 500
    nA = 510
    rMas = np.linspace(0,1,nr);
    AMas = np.linspace(0,10,nA);
    LossM = np.zeros((nr,nA));
    
    
    def compute(ir, iA, r0, A0):
        return ir, iA, LossFun([r0, A0], dt, Texp, Vexp)

    results = Parallel(n_jobs=-1)(
        delayed(compute)(ir, iA, r0, A0)
        for ir, r0 in enumerate(rMas)
        for iA, A0 in enumerate(AMas)
    )

    LossM = np.zeros((nr, nA))
    for ir, iA, val in results:
        LossM[ir, iA] = val
             
                
    mdict = {"rMas":rMas, "AMas":AMas, "LossM":LossM} 
    sio.savemat("Loss_sync.mat",mdict)
            
    fig, ax = plt.subplots(nrows=1, figsize=(6,10))
    im = ax.imshow(LossM)
    cb = plt.colorbar(im)
    
    
    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    main()




