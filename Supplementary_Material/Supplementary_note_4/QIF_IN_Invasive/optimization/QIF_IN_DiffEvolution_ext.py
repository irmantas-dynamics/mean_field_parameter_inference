"""
This script optimizes the parameters of the macroscopic equations for QIF neurons
to fit a signal generated by microscopic equation-based modeling. 

ODE is defined in  "Firing rate equations require a spike synchrony mechanism
to correctly describe fast oscillations in inhibitory networks" by F. Devalle, A. Roxin
and E. Montbrió https://doi.org/10.1371/journal.pcbi.1005881

To avoid dependence of the loss function on the initial conditions of the ODE. To avoid dependence of the loss function on the initial conditions of the ODE the
microscopic equations is affected  with known external periodic  force, which syncrhonizes
the system.

Optimization is performed using Differential Evolution algorithm implemented in
scipy package. The algorithm uses parallel computing. Set the workers option in
differential_evolution() according to your CPU capabilities.

Script's input:

        Narray: array with strings representing neuron counts used for macroscopic signal
                generation, used for file with macroscopic signal loading.
                File name format "../time_series_rand/QIF_IN_N%s_%d.txt", where %s is element
                of Narray.
                
        nopt:   number of different DE optimization trials

Script writes results to file with name format - optimization_results/QIF_IN_%s_optim_results.csv
, where %s is neuron counts used for macroscopic signal generation. Columns correspond to
optimized parameters; the last column contains the optimized loss value.


"""
import time                                         # for benchmarking each optimisation trial
import numpy as np                                    # array math and contiguous buffer handling
import ctypes                                         # C shared-library interface (losslib)
from scipy.optimize import differential_evolution     # global optimiser
import scipy.io as sio                                # loading MATLAB .mat data files

from functools import partial                         # binds fixed args to LossFun for DE

import ctypes

from scipy.optimize import differential_evolution


import scipy.io as sio

from functools import partial

# Load the shared library
lib = ctypes.CDLL('./liblosslib.so')  # adjust path/extension for Windows or macOS

# Define argument types for compute_rmse
lib.compute_rmse.argtypes = [
    ctypes.c_double,    #taum
    ctypes.c_double,    #etab
    ctypes.c_double,    #J
    ctypes.c_double,    #delta
    ctypes.c_double,    #taua
    ctypes.c_double,    #Kamp
    ctypes.c_double,    #Kom
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'), #Texp
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'), #Vexp
    ctypes.c_int,    # n
    ctypes.c_int,    # nTtr
    ctypes.c_int    # nDt
]
lib.compute_rmse.restype = ctypes.c_double

# Define argument types for lossPar
lib.lossPar.argtypes = [
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # taum_vals
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # etab_vals
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # J_vals
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # delta_vals
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # taua
    ctypes.c_int,     # n_params
    ctypes.c_double,  # KAmp
    ctypes.c_double,  # Kom
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # Texp
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS'),  # Vexp
    ctypes.c_int,     # n
    ctypes.c_int,    # nTtr
    ctypes.c_int,    # nDt
    np.ctypeslib.ndpointer(dtype=np.float64, ndim=1, flags='C_CONTIGUOUS')   # rmse_par (output)
]
lib.lossPar.restype = None



# ---------------------------------------------------------------------------
# Loss function
# ---------------------------------------------------------------------------
def LossFun(p,interp_Yexp, dt, Texp, Vexp):
    """
    Vectorised loss function called by differential_evolution (vectorized=True).

    Parameters
    ----------
    p : ndarray, shape (5, n_params)
        Population matrix from DE; each column is one candidate:
        row 0 – delta, row 1 – J, row 2 – etab, row 3 – beta, row 4 – taum.
    interp_Yexp : unused placeholder (kept for API compatibility with partial())
    dt          : float  – integration time step of the experimental signal
    Texp        : 1-D array – time axis of the experimental signal
    Vexp        : 1-D array – mean membrane potential from the microscopic sim

    Returns
    -------
    loss : 1-D array of length n_params
    """

    
    # parameters used in signal generation
    delta= 0.3;    
    J    = 21;
    etab = 4;
    taum = 10;
    taua = 5;
    

    p = np.ascontiguousarray(p, dtype=np.float64)  # ensure contiguous

    n_params = p.shape[1]

    # [delta, J, etab, taum, taua]
    delta_vals = p[0,:]
    J_vals     = p[1,:]
    etab_vals  = p[2,:]
    taum_vals  = p[3,:]
    taua_vals  = p[4,:]
    

    # Ensure arrays are contiguous float64 for C
    delta_vals = np.ascontiguousarray(delta_vals, dtype=np.float64)
    J_vals     = np.ascontiguousarray(J_vals, dtype=np.float64)
    etab_vals  = np.ascontiguousarray(etab_vals, dtype=np.float64)
    taum_vals  = np.ascontiguousarray(taum_vals, dtype=np.float64)
    taua_vals  = np.ascontiguousarray(taua_vals, dtype=np.float64)

    Texp = np.ascontiguousarray(Texp, dtype=np.float64)
    Vexp = np.ascontiguousarray(Vexp, dtype=np.float64)
    
    
    KAmp = -0.45
    KTper= 28.0
    Kom = 2*np.pi/KTper
    
    
    # gradient evaluation time
    Dt = 20*KTper
    # transient time
    Ttr = 50*KTper
    
    nTtr = np.round((Ttr)/dt)
    nTtr = nTtr.astype(int)
    nDt = np.round((Dt)/dt)
    nDt = nDt.astype(int)
    
  
    
    # delta_vals = delta_vals.astype(np.float64)
    # J_vals     = J_vals.astype(np.float64) 
    # etab_vals  = etab_vals.astype(np.float64) 
    # beta_vals  = beta_vals.astype(np.float64) 
    # taum_vals  = taum_vals.astype(np.float64) 
    
    #print(a_vals)
    #print(b_vals)

    # Output array for RMSE
    loss = np.empty(n_params, dtype=np.float64)

    # --- call the OpenMP-parallelised C batch evaluator ---
    lib.lossPar(
                taum_vals,
                etab_vals,
                J_vals,
                delta_vals,
                taua_vals,
                n_params,
                KAmp,
                Kom,
                Texp,
                Vexp,
                len(Texp),
                nTtr,
                nDt,
                loss
                )
    # lib.lossPar(
    #             taum_vals.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             etab_vals.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             J_vals.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             delta_vals.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             beta_vals.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             taua,
    #             n_params,
    #             KAmp,
    #             Kom,
    #             Texp.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             Vexp.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
    #             len(Texp),
    #             loss
    #             )
    return loss
    



def main():
    """
    Entry point.

    For each neuron count in Narray:
      1. Load the microscopic simulation signal from a .txt file.
      2. Run nopt independent DE optimisations, each starting from a
         different random population.
      3. Append optimised parameters and loss values to a per-N CSV file.
         Timing for each trial is written to a shared time.csv.
    """


    Narray=['100000','10000','1000','500','200']


    # Number of independent DE optimisation trials per neuron count
    nopt = 1
    for ind in Narray:
        # DE optimization trials
        for i1 in range(0,nopt):         
            # loading macroscopic signal from file
            fname = "../time_series_rand/QIF_IN_N%s_%d_ext.txt" % (ind, i1+1)
            vrs = np.loadtxt(fname)
            print("========\tFile:\t%s\t loaded\t ==============\n"% fname)
            print(np.shape(vrs))

            # mean potential signal
            Vexp = vrs[:,2]
            # time
            Texp = vrs[:,0]
            # integration step
            dt = Texp[1]-Texp[0]#vrs['dt']

            interp_Yexp = 0

            # bound for parameter optimization
            # [delta, J, etab, taum, taua]
            bounds = [(0.07,0.7),(10., 30.),(1.75,4.9),(0.25,15),(1.,17.)]

            # DE optimization trials
            
            loss = partial(LossFun,interp_Yexp=interp_Yexp, dt=dt, Texp=Texp, Vexp=Vexp)


            start_time = time.time()

            # vectorized=True lets DE pass the whole population matrix at once,
            # so lossPar can evaluate all candidates in a single OpenMP-parallel
            # C call instead of one Python call per candidate.
            result = differential_evolution(loss,
                                        bounds,
                                        disp = True,
                                        popsize= 15,
                                        maxiter = 500,
                                        atol=1e-5,
                                        tol = 1e-5,
                                        vectorized = True,
                                        polish = False,
                                        updating='deferred',
                                        #seed = 1
                                        );

            print("\n--- %d iteration finished in" % (i1+1), end =' ')
            total_time = (time.time() - start_time)
            print(" %s seconds ---\n" % total_time)

            # Append wall-clock time for this trial
            with open("optimization_results/time.csv","a") as f:
                f.write("%s; %f\n" % (ind,total_time))
                
            # Append optimised parameters and final loss to the per-N CSVe
            fname2 = "optimization_results/QIF_IN_%s_optim_results_ext.csv" % ind

            print("Optimized parameters:")
            
            with open(fname2,"a") as f:
                    for i2 in range(0,len(bounds)):
                        f.write("%f;" % result.x[i2])
                        print(result.x[i2], end=' ')
                
                    print("\n\nValues of loss function:")
                    print(result.fun)
                    print()
                    f.write("%e;\n" % result.fun)
                    
                
            print("============================\n\n")




    
if __name__ == "__main__":
    main()





